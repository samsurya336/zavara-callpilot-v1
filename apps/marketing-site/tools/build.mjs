#!/usr/bin/env node
/* Build step for static hosts (Render, Netlify, Vercel, ...).
   Copies the site into dist/ and writes dist/js/config.js from environment variables, so the
   application URL is configured per deployment instead of being committed.

   Usage:   node tools/build.mjs            (run from apps/marketing-site)
   Env:     APP_URL   address of the CallPilot application for every "Get started" button.
                      Leave unset or empty while the app is not open: buttons then fall back
                      to the in-page "Early access" section. */
import { createHash } from 'node:crypto'
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dist = join(root, 'dist')
const appUrl = (process.env.APP_URL || '').trim()

if (appUrl && !/^https?:\/\//i.test(appUrl)) {
  console.error(`APP_URL must start with http:// or https:// (got "${appUrl}")`)
  process.exit(1)
}

rmSync(dist, { recursive: true, force: true })
mkdirSync(dist)
for (const entry of ['index.html', 'roadmap.html', '404.html', 'css', 'js', 'assets']) {
  cpSync(join(root, entry), join(dist, entry), { recursive: true })
}

const config =
  '/* Generated by tools/build.mjs. Do not edit; set APP_URL instead. */\n' +
  `window.CALLPILOT_CONFIG = ${JSON.stringify({ appUrl }, null, 2)};\n`
writeFileSync(join(dist, 'js', 'config.js'), config)

// config.js keeps its filename but its content changes per deployment, so give the script tag a
// content-hash query. Browsers and the CDN then fetch the new version instead of a cached one,
// whatever Cache-Control the host applies to /js/*.
const configHash = createHash('sha256').update(config).digest('hex').slice(0, 10)
for (const page of ['index.html', 'roadmap.html', '404.html']) {
  const file = join(dist, page)
  const html = readFileSync(file, 'utf8')
  const updated = html.replace(/js\/config\.js(\?v=[^"']*)?/g, `js/config.js?v=${configHash}`)
  if (updated === html) {
    console.error(`${page}: could not find the js/config.js script tag to version`)
    process.exit(1)
  }
  writeFileSync(file, updated)
}

console.log(`built dist/ (APP_URL ${appUrl ? `= ${appUrl}` : 'not set: "Get started" stays on the page'})`)
